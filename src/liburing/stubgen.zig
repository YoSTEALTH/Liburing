//! `zig build stubs`: prints `liburing.pyi`, the type stubs for `liburing.liburing`, built at
//! comptime by `setu.stub` from the classes and files listed in `api.zig`. It runs on the
//! build machine and never calls Python, so it needs no libpython.

const std = @import("std");
const setu = @import("setu");
const api = @import("api.zig");

/// Setu settings, read by `setu.Class` from the root file.
pub const setu_options = api.setu_options;

const header =
    \\# Type stubs for `liburing.liburing`, generated by `zig build stubs` (`src/liburing/stubgen.zig`)
    \\# from the `///` docs and Zig types: edit those, not this file.
    \\
    \\import os
    \\from collections.abc import Buffer, Generator, Sequence
    \\from enum import IntEnum
    \\from typing import Any, ClassVar, Self, final
    \\
    \\from typing_extensions import disjoint_base  # `typing` has it from 3.15 (PEP 800); stubs cover 3.14 too
    \\
    \\__version__: str
    \\LIBURING_HAVE_DATA64: str
    \\
    \\class UnsupportedError(OSError):
    \\    """The running kernel does not support this `io_uring` feature (`errno` is the kernel's: `EINVAL`, ...)."""
    \\
;

/// `class Name(IntEnum):` with its members, for an enum `api.enums` exports.
fn intEnum(comptime E: type) []const u8 {
    const full = @typeName(E);
    const name = full[(std.mem.lastIndexOfScalar(u8, full, '.') orelse return full) + 1 ..];
    var out: []const u8 = "\nclass " ++ name ++ "(IntEnum):\n";
    for (@typeInfo(E).@"enum".field_names) |f| out = out ++ "    " ++ f ++ " = " ++
        std.fmt.comptimePrint("{d}", .{@backingInt(@field(E, f))}) ++ "\n";
    return out;
}

/// The whole `.pyi`: constants, enums, classes, then functions.
const text = blk: {
    @setEvalBranchQuota(100_000_000);
    var out: []const u8 = header;
    for (api.constant_files) |F| out = out ++ setu.stub.constants(F);
    for (api.enums) |E| out = out ++ intEnum(E);
    for (api.classes) |C| out = out ++ setu.stub.class(C);
    for (api.files) |f| out = out ++ setu.stub.functions(f.M, f.source);
    break :blk setu.stub.format(out);
};

/// Writes `text` to stdout.
pub fn main() void {
    var rest: []const u8 = text;
    while (rest.len > 0) {
        const n = std.os.linux.write(1, rest.ptr, rest.len);
        if (@as(isize, @bitCast(n)) <= 0) std.process.exit(1);
        rest = rest[n..];
    }
}
